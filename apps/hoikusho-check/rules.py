# --- 基準指数（代表値。父母それぞれの事由・就労状況から算出） ---
# 就労・介護・就学は「月あたり日数 × 1日あたり就労時間」で決まる。ここでは代表的な段階のみ。
def kijun_shisu_work(days_per_month: int, hours_per_day: float, is_naitei: bool = False) -> int:
    """就労（内定含む）の基準指数の目安。ごあんない p.20 の抜粋を簡略化。"""
    base = 8
    if days_per_month >= 20 and hours_per_day >= 8:
        base = 20
    elif days_per_month >= 20 and hours_per_day >= 6:
        base = 17
    elif days_per_month >= 20 and hours_per_day >= 4:
        base = 14
    elif days_per_month >= 16 and hours_per_day >= 8:
        base = 17
    elif days_per_month >= 16 and hours_per_day >= 4:
        base = 12
    elif days_per_month >= 12:
        base = 10
    else:
        base = 8  # 月48時間以上が最低ライン。これ未満は原則対象外
    if is_naitei:
        base = max(2, base - 6)  # 内定は実働より低め（簡略化）
    return base


